// Builds two files from src/data/terms and cases.json:
//
// - src/data/skeleton.json, which the app ships with: areas and units, with how many terms each
//   unit has, and each desk case's opening and length. No term names or ids: the app learns a
//   term's name from the server once the learner reaches it (see worker/terms.ts).
// - src/data/outline.json, which only the Worker and the tests read: each term's name, unit,
//   difficulty and mix-ups, never what it means. The term cards (definition, examples, questions
//   and answers) and the cases and game content stay on the server too (see worker/cards.ts).
//
//   node scripts/build-outline.mjs          write both
//   node scripts/build-outline.mjs --check  fail if either is out of date
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data');
const termsDir = join(root, 'terms');
const out = join(root, 'outline.json');
const skeletonOut = join(root, 'skeleton.json');
const check = process.argv.includes('--check');

const categories = readdirSync(termsDir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(termsDir, f), 'utf8')))
  .sort((a, b) => a.order - b.order);

// The same whole-phrase match as src/lib/questions.ts (phraseHits), plurals included.
const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const hits = (text, name) => [...text.matchAll(new RegExp(`(^|[^\\w-])(${escapeRegExp(name)}(?:s|es)?)(?![\\w-])`, 'gi'))].length > 0;
const names = (x) => [x.term, ...(x.aliases ?? [])].filter((n) => n.length >= 2);
// Whether y's definition or gloss names x.
const named = (x, y) => names(x).some((n) => hits(`${y.definition} ${y.short}`, n));

/**
 * Terms of the same area that this term's definition names, or whose definition names it.
 * Questions leave them out as wrong options in an example sentence, where they could fit too.
 * Worked out here because it needs the definitions, which the app no longer has for every term.
 */
function near(term, cat) {
  return cat.terms.filter((t) => t.id !== term.id && (named(t, term) || named(term, t))).map((t) => t.id);
}

const cases = JSON.parse(readFileSync(join(root, 'cases.json'), 'utf8'));
const phase3Units = new Set(categories.filter((c) => c.phase === 3).flatMap((c) => c.units.map((u) => u.id)));

const skeleton = {
  note: 'Generated by scripts/build-outline.mjs from src/data/terms and cases.json. Do not edit by hand.',
  // Shown on a case's unit sheet before it starts: the setup, and how many decisions it has.
  // A phase 3 case's setup comes with the case, once phase 3 is open.
  cases: Object.fromEntries(Object.entries(cases).map(([id, c]) => [id, phase3Units.has(id) ? { steps: c.steps.length } : { setup: c.setup, steps: c.steps.length }])),
  // Each unit with its number of terms: what the path, the unlock rules and the counts need.
  categories: categories.map((c) => ({
    id: c.id,
    name: c.name,
    order: c.order,
    ...(c.phase ? { phase: c.phase } : {}),
    units: c.units.map((u) => ({ ...u, size: c.terms.filter((t) => t.unit === u.id).length })),
  })),
};

const outline = {
  note: 'Generated by scripts/build-outline.mjs from src/data/terms. Do not edit by hand. Read by the Worker and the tests only: never part of the app.',
  categories: categories.map((c) => ({
    id: c.id,
    name: c.name,
    order: c.order,
    ...(c.phase ? { phase: c.phase } : {}),
    units: c.units,
    terms: c.terms.map((t) => {
      const n = near(t, c);
      return {
        id: t.id,
        term: t.term,
        ...(t.aliases?.length ? { aliases: t.aliases } : {}),
        ...(t.said ? { said: t.said } : {}),
        ...(t.speak ? { speak: t.speak } : {}),
        unit: t.unit,
        difficulty: t.difficulty,
        confusables: t.confusables,
        ...(t.overlaps?.length ? { overlaps: t.overlaps } : {}),
        ...(n.length ? { near: n } : {}),
      };
    }),
  })),
};

const files = [
  [out, JSON.stringify(outline, null, 1) + '\n'],
  [skeletonOut, JSON.stringify(skeleton, null, 1) + '\n'],
];
if (check) {
  for (const [f, text] of files) {
    if (!existsSync(f) || readFileSync(f, 'utf8') !== text) {
      console.error(`${f.slice(f.indexOf('src/'))} is out of date. Run: node scripts/build-outline.mjs`);
      process.exit(1);
    }
  }
  console.log('Outline and skeleton are up to date.');
} else {
  for (const [f, text] of files) writeFileSync(f, text);
  console.log(`Wrote src/data/outline.json and skeleton.json: ${categories.length} areas, ${categories.reduce((n, c) => n + c.terms.length, 0)} terms.`);
}
