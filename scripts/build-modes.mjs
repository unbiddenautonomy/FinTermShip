// Builds the data the Term Lines and Recall Exchange modes read, straight from the syllabus.
// Nothing here edits the syllabus: lines follow the areas, stops follow the units and the
// term order exactly as Path teaches them, and interchanges come from the confusables.
//
// It also checks the Headline Desk and Finnections content (headlines.json, finnections.json)
// and writes rounds.json: each item's id, level and terms, with no text. The app ships that
// index so it can tell which items a learner can play before the content itself arrives from
// the server. A board's terms are sorted, so the index never gives its groups away.
//
//   node scripts/build-modes.mjs          write src/data/modes/metro.json, tickers.json and rounds.json
//   node scripts/build-modes.mjs --check  fail if any of them is out of date, or the content is broken
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data');
const termsDir = join(root, 'terms');
const modesDir = join(root, 'modes');
const check = process.argv.includes('--check');

const files = readdirSync(termsDir).filter((f) => f.endsWith('.json')).sort();
const sources = files.map((f) => readFileSync(join(termsDir, f), 'utf8'));
const categories = sources.map((s) => JSON.parse(s)).sort((a, b) => a.order - b.order);
const syllabusHash = createHash('sha256').update(sources.join('\n')).digest('hex').slice(0, 16);

const catOf = new Map();
const unitOf = new Map();
for (const c of categories) for (const t of c.terms) { catOf.set(t.id, c.id); unitOf.set(t.id, t.unit); }

// Lines: one per area. Stops: each unit in syllabus order; a unit of terms gives one stop per
// term in file order, and a practice unit (drill, game, case) gives one depot.
const lines = categories.map((c) => {
  const stops = [];
  const units = [];
  for (const u of c.units) {
    const from = stops.length;
    if (u.kind && u.kind !== 'terms') stops.push({ depot: u.id, kind: u.kind, ...(u.game ? { game: u.game } : {}) });
    else for (const t of c.terms) if (t.unit === u.id) stops.push({ term: t.id });
    units.push({ id: u.id, name: u.name, core: !!u.core, from, to: stops.length - 1 });
  }
  return { id: c.id, name: c.name, order: c.order, ...(c.phase ? { phase: c.phase } : {}), units, stops };
});

// Interchanges: every pair of terms in different areas that either one lists as a confusable.
// Pairs inside one area are "neighbours" on the same line, used for Transfer puzzles too.
const pairKey = (a, b) => (a < b ? `${a}|${b}` : `${b}|${a}`);
const seen = new Map();
for (const c of categories) for (const t of c.terms) for (const o of t.confusables) {
  if (!catOf.has(o) || o === t.id) continue;
  const k = pairKey(t.id, o);
  seen.set(k, (seen.get(k) ?? 0) + 1);
}
const interchanges = [];
const neighbours = [];
for (const [k, n] of [...seen].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const [a, b] = k.split('|');
  const entry = { a, b, both: n === 2 };
  (catOf.get(a) === catOf.get(b) ? neighbours : interchanges).push(entry);
}
// Unit links: the network map draws one connector per pair of units in different areas that share interchanges.
const unitLinks = new Map();
for (const { a, b } of interchanges) {
  const k = pairKey(unitOf.get(a), unitOf.get(b));
  unitLinks.set(k, (unitLinks.get(k) ?? 0) + 1);
}
const metro = {
  note: 'Generated by scripts/build-modes.mjs from src/data/terms. Do not edit by hand.',
  syllabus: syllabusHash,
  lines,
  interchanges,
  neighbours,
  unitLinks: [...unitLinks].sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, n]) => { const [a, b] = k.split('|'); return { a, b, n }; }),
};

// Tickers: short, readable, unique and never reassigned. Existing tickers are kept; only new terms get one.
const tickerPath = join(modesDir, 'tickers.json');
const old = existsSync(tickerPath) ? JSON.parse(readFileSync(tickerPath, 'utf8')) : {};
const tickers = {};
const used = new Set();
const allIds = categories.flatMap((c) => c.terms.map((t) => t.id));
for (const id of allIds) if (old[id]) { tickers[id] = old[id]; used.add(old[id]); }
const STOP = new Set(['a', 'an', 'the', 'of', 'to', 'on', 'in', 'and', 'or', 'for', 'is', 'it', 'its', 'your', 'you']);
function candidates(t) {
  const squash = (x) => x.replace(/[’']/g, '').replace(/&/g, 'AND').split(/[^A-Za-z0-9+]+/).filter(Boolean);
  const out = [];
  // A short all-caps alias or term is already how the desk says it: LTP, IV, STT.
  for (const a of [t.term, ...(t.aliases || [])]) {
    const s = squash(a).join('');
    if (/^[A-Z0-9+]{2,8}$/.test(s)) out.push(s);
  }
  const words = squash(t.term);
  const joined = words.join('').toUpperCase();
  if (joined.length <= 10) out.push(joined);
  const content = words.filter((w) => !STOP.has(w.toLowerCase()));
  if (content.length > 1) {
    out.push((content[0].slice(0, 7) + content.slice(1).map((w) => w[0]).join('')).toUpperCase().slice(0, 10));
    const initials = content.map((w) => w[0]).join('').toUpperCase();
    if (initials.length >= 3) out.push(initials);
  }
  out.push(joined.slice(0, 10));
  return out.filter((s) => s.length >= 2);
}
for (const c of categories) for (const t of c.terms) {
  if (tickers[t.id]) continue;
  let pick = candidates(t).find((s) => !used.has(s));
  if (!pick) { const base = candidates(t)[0].slice(0, 6); let i = 2; while (used.has(base + i)) i++; pick = base + i; }
  tickers[t.id] = pick;
  used.add(pick);
}
for (const id of Object.keys(old)) if (!allIds.includes(id)) tickers[id] = old[id]; // retired terms keep theirs, so no ticker is ever reused

// Headline Desk and Finnections: check every item, then index them.
const known = new Set(allIds);
const problems = [];
const levelOk = (x) => x === 1 || x === 2 || x === 3;
const headlines = JSON.parse(readFileSync(join(modesDir, 'headlines.json'), 'utf8'));
const boards = JSON.parse(readFileSync(join(modesDir, 'finnections.json'), 'utf8'));
const ids = new Set();
for (const h of headlines) {
  if (ids.has(h.id)) problems.push(`${h.id}: id used twice`);
  ids.add(h.id);
  if (!levelOk(h.level)) problems.push(`${h.id}: level must be 1, 2 or 3`);
  if (!h.head || !h.dek || !h.why) problems.push(`${h.id}: needs a head, a dek and a why`);
  if (!Array.isArray(h.items) || h.items.length < 2 || h.items.length > 4) problems.push(`${h.id}: needs 2 to 4 items`);
  for (const i of h.items ?? []) {
    if (!known.has(i.term)) problems.push(`${h.id}: no term '${i.term}'`);
    if (i.move !== 'up' && i.move !== 'down') problems.push(`${h.id}: '${i.label}' must move up or down`);
    if (!i.label) problems.push(`${h.id}: an item has no label`);
  }
  if (new Set((h.items ?? []).map((i) => i.label)).size !== (h.items ?? []).length) problems.push(`${h.id}: two items share a label`);
}
for (const b of boards) {
  if (ids.has(b.id)) problems.push(`${b.id}: id used twice`);
  ids.add(b.id);
  if (!levelOk(b.level)) problems.push(`${b.id}: level must be 1, 2 or 3`);
  if (!Array.isArray(b.groups) || b.groups.length !== 4) problems.push(`${b.id}: needs 4 groups`);
  const terms = (b.groups ?? []).flatMap((g) => g.terms ?? []);
  if (terms.length !== 16 || new Set(terms).size !== 16) problems.push(`${b.id}: needs 16 different terms, 4 to a group`);
  for (const g of b.groups ?? []) {
    if (!g.name || !g.why) problems.push(`${b.id}: group '${g.name}' needs a name and a why`);
    if ((g.terms ?? []).length !== 4) problems.push(`${b.id}: group '${g.name}' needs 4 terms`);
    for (const t of g.terms ?? []) if (!known.has(t)) problems.push(`${b.id}: no term '${t}'`);
  }
  // Tiles show term names, so two tiles with the same name would make a board unsolvable.
  const names = terms.map((t) => categories.flatMap((c) => c.terms).find((x) => x.id === t)?.term.toLowerCase());
  if (new Set(names).size !== names.length) problems.push(`${b.id}: two tiles have the same name`);
}
if (problems.length) {
  console.error(`Headline Desk and Finnections content has ${problems.length} problems:`);
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}
const termsOf = (x) => [...new Set(x.items ? x.items.map((i) => i.term) : x.groups.flatMap((g) => g.terms))].sort();
const rounds = {
  note: 'Generated by scripts/build-modes.mjs from headlines.json and finnections.json. Do not edit by hand.',
  headline: headlines.map((h) => [h.id, h.level, ...termsOf(h)]),
  finnections: boards.map((b) => [b.id, b.level, ...termsOf(b)]),
};
const compact = (o) => '{\n' + Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ` + (Array.isArray(v) ? '[\n' + v.map((r) => `    ${JSON.stringify(r)}`).join(',\n') + '\n  ]' : JSON.stringify(v))).join(',\n') + '\n}\n';

const outputs = [
  [join(modesDir, 'metro.json'), JSON.stringify(metro, null, 2) + '\n'],
  [tickerPath, JSON.stringify(tickers, null, 2) + '\n'],
  [join(modesDir, 'rounds.json'), compact(rounds)],
];
let stale = 0;
for (const [path, text] of outputs) {
  const cur = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (cur === text) continue;
  if (check) { console.error(`${path.split('/src/')[1]} is out of date: run node scripts/build-modes.mjs`); stale++; }
  else writeFileSync(path, text);
}
if (stale) process.exit(1);
const stations = lines.reduce((n, l) => n + l.stops.filter((s) => s.term).length, 0);
const depots = lines.reduce((n, l) => n + l.stops.filter((s) => s.depot).length, 0);
console.log(`Term Lines: ${lines.length} lines, ${stations} stations, ${depots} depots, ${interchanges.length} interchanges, ${neighbours.length} same-line pairs, ${metro.unitLinks.length} unit links`);
console.log(`Tickers: ${Object.keys(tickers).length}`);
const byLevel = (xs) => [1, 2, 3].map((l) => xs.filter((x) => x.level === l).length).join('/');
console.log(`Headline Desk: ${headlines.length} headlines (${byLevel(headlines)} by level). Finnections: ${boards.length} boards (${byLevel(boards)}).`);
